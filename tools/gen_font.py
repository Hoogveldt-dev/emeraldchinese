#!/usr/bin/env python3
"""Build the CJK glyph table and the 2-byte encoding for the Chinese build.

Encoding: a lead byte from LEADS (codes with no Latin glyph and no control
meaning in the English game) followed by a trail byte 0x01..0xF6.
Glyphs: WenQuanYi Bitmap Song 12px (GPL-2 with font embedding exception),
11 rows of 11 pixels, advance 12.

Writes:
  out/3ds_cjk_font.c   glyph rows + lead table, compiled into the 3DSX
  out/cjk_table.json   char -> [lead, trail], for the localizer and the tool
"""
import json, sys
from pathlib import Path

LEADS = ([0x33] + list(range(0x38, 0x51)) + list(range(0x5E, 0x68)) + list(range(0x69, 0x6F))
         + list(range(0x70, 0x77)) + [0x78] + list(range(0x7D, 0x84)) + list(range(0x87, 0xA0)))
TRAIL_MIN, TRAILS = 0x01, 246
CAPACITY = len(LEADS) * TRAILS


def load_bdf(path):
    glyphs, cur = {}, None
    for line in open(path, encoding="latin-1"):
        if line.startswith("ENCODING"):
            cur = {"enc": int(line.split()[1])}
        elif cur is not None and line.startswith("BBX"):
            cur["bbx"] = list(map(int, line.split()[1:]))
        elif cur is not None and line.startswith("DWIDTH"):
            cur["dw"] = int(line.split()[1])
        elif line.startswith("BITMAP"):
            cur["rows"] = []
        elif line.startswith("ENDCHAR"):
            glyphs[cur["enc"]] = cur
            cur = None
        elif cur is not None and "rows" in cur:
            cur["rows"].append(line.strip())
    return glyphs


def cell(g, ascent=12):
    """The glyph as 12 rows of a 12-px cell (bit 11 = leftmost), baseline at row 10."""
    w, h, xo, yo = g["bbx"]
    rows = [0] * 12
    nbits = len(g["rows"][0]) * 4 if g["rows"] else 8
    top = 10 - (yo + h)  # row of the glyph's first line: baseline 10 = 11px tall cell top at 0
    for i, hexrow in enumerate(g["rows"]):
        bits = int(hexrow, 16)
        y = top + i + 1
        if not 0 <= y < 12:
            continue
        for x in range(w):
            if bits >> (nbits - 1 - x) & 1:
                px = xo + x
                if 0 <= px < 12:
                    rows[y] |= 1 << (11 - px)
    return rows


def charset(glyphs):
    order, seen = [], set()

    def add(c):
        if c not in seen and ord(c) in glyphs:
            seen.add(c)
            order.append(c)
    # GB2312 symbols and hanzi first (rows 0xA1-0xA9, 0xB0-0xF7), then the rest.
    for hi in list(range(0xA1, 0xAA)) + list(range(0xB0, 0xF8)):
        for lo in range(0xA1, 0xFF):
            try:
                add(bytes([hi, lo]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    for lo, hi in ((0x3000, 0x303F), (0xFF00, 0xFFEF), (0x2010, 0x206F), (0x4E00, 0x9FFF)):
        for cp in range(lo, hi + 1):
            if len(order) >= CAPACITY:
                break
            add(chr(cp))
    # ASCII and Latin-1 letters stay in the game's own font.
    order = [c for c in order if ord(c) > 0x2000]
    return order[:CAPACITY]


def main():
    bdf, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    glyphs = load_bdf(bdf)
    chars = charset(glyphs)
    table = {}
    rows_c = []
    for i, ch in enumerate(chars):
        lead, trail = LEADS[i // TRAILS], TRAIL_MIN + i % TRAILS
        table[ch] = [lead, trail]
        rows = cell(glyphs[ord(ch)])
        rows_c.append("{" + ",".join("0x%03X" % r for r in rows) + "}")
    lead_index = [0xFF] * 256
    for n, lead in enumerate(LEADS):
        lead_index[lead] = n
    src = ["/* Generated by gen_font.py from WenQuanYi Bitmap Song 12px",
           " * (GPL-2 with font embedding exception). Do not edit. */",
           "const unsigned char gCjkLeadIndex[256] = {" + ",".join(str(x) for x in lead_index) + "};",
           "const unsigned int gCjkGlyphCount = %d;" % len(chars),
           "const unsigned short gCjkGlyphs[%d][12] = {" % len(chars)]
    for i in range(0, len(rows_c), 4):
        src.append(",".join(rows_c[i:i + 4]) + ",")
    src.append("};")
    (out / "3ds_cjk_font.c").write_text("\n".join(src) + "\n")
    (out / "cjk_table.json").write_text(json.dumps({"leads": LEADS, "trail_min": TRAIL_MIN,
                                                    "trails": TRAILS, "chars": "".join(chars)},
                                                   ensure_ascii=False))
    print("glyphs:", len(chars), "capacity:", CAPACITY)


if __name__ == "__main__":
    main()
